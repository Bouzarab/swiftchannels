/* ═══════════════════════════════════════════════════════════════════
   ENGINE — shared by index.html and thank-you.html.
   Nothing below needs editing to change wording; edit the tables above.
   ═══════════════════════════════════════════════════════════════════ */
window.i18n = (function(){
  const DICT  = window.I18N || {};
  const LANGS = ['en','fr','es','de','it','nl'];
  let LANG = 'en';

  const norm = s => String(s).replace(/\s+/g,' ').trim();

  function t(s){
    if(LANG === 'en' || !s) return s;
    const d = DICT[LANG];
    return (d && d[norm(s)]) || s;
  }
  function tf(s, vars){
    let out = t(s);
    for(const k in vars) out = out.split('{' + k + '}').join(vars[k]);
    return out;
  }

  const NODES = [], ATTRS = [], HTMLS = [], META = {};
  let SKIP = '';

  function snapshot(skipSelector){
    SKIP = skipSelector || '';
    META.title = document.title;
    const md = document.querySelector('meta[name="description"]');
    META.desc = md ? md.getAttribute('content') : '';

    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      HTMLS.push({ el, key: el.getAttribute('data-i18n-html'), en: el.innerHTML });
    });

    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let n;
    while((n = walker.nextNode())){
      if(!/\S/.test(n.nodeValue)) continue;
      const el = n.parentElement;
      if(!el || el.tagName === 'SCRIPT' || el.tagName === 'STYLE') continue;
      if(el.closest('svg') || el.closest('[data-i18n-html]')) continue;
      if(SKIP && el.closest(SKIP)) continue;
      const raw = n.nodeValue;
      NODES.push({
        node: n, en: norm(raw),
        pre: raw.match(/^\s*/)[0], post: raw.match(/\s*$/)[0]
      });
    }

    ['placeholder','title','aria-label','alt'].forEach(a => {
      document.querySelectorAll('[' + a + ']').forEach(el => {
        ATTRS.push({ el, a, en: el.getAttribute(a) });
      });
    });
  }

  let arabicFont = false;
  function loadArabicFont(){
    if(arabicFont) return;
    arabicFont = true;
    const l = document.createElement('link');
    l.rel = 'stylesheet';
    l.href = 'https://fonts.googleapis.com/css2?family=Cairo:wght@600;700;800' +
             '&family=Tajawal:wght@400;500;700&display=swap';
    document.head.appendChild(l);
  }

  let onApply = null;
  let titleKey = '__meta_title';
  let descKey  = '__meta_desc';

  function apply(lang, remember){
    LANG = (lang === 'en' || DICT[lang]) ? lang : 'en';
    const rtl = LANG === 'ar';
    if(rtl) loadArabicFont();

    const h = document.documentElement;
    h.setAttribute('lang', LANG);
    h.setAttribute('dir', rtl ? 'rtl' : 'ltr');

    NODES.forEach(o => { o.node.nodeValue = o.pre + t(o.en) + o.post; });
    ATTRS.forEach(o => o.el.setAttribute(o.a, t(o.en)));
    HTMLS.forEach(o => {
      const d = DICT[LANG];
      o.el.innerHTML = (d && d[o.key]) || o.en;
    });

    const d = DICT[LANG] || {};
    document.title = d[titleKey] || META.title;
    const md = document.querySelector('meta[name="description"]');
    if(md) md.setAttribute('content', d[descKey] || META.desc);

    document.querySelectorAll('.lang-b').forEach(b => {
      b.setAttribute('aria-current', String(b.dataset.lang === LANG));
    });
    /* the collapsed button shows the active flag */
    const cur = document.getElementById('langCur');
    if(cur){
      const active = document.querySelector('.lang-b[data-lang="' + LANG + '"] img');
      const slot = cur.querySelector('img');
      if(active && slot){
        slot.setAttribute('src', active.getAttribute('src'));
        slot.setAttribute('alt', '');
      } else {
        cur.textContent = LANG.toUpperCase();
      }
    }

    if(onApply) onApply(LANG);

    if(remember !== false){ try { localStorage.setItem('lang', LANG); } catch(e){} }
  }

  function initial(){
    const q = new URLSearchParams(location.search).get('lang');
    if(q && LANGS.includes(q)) return q;
    try {
      const saved = localStorage.getItem('lang');
      if(saved && LANGS.includes(saved)) return saved;
    } catch(e){}
    const nav = (navigator.languages || [navigator.language || 'en'])
      .map(x => String(x).slice(0,2).toLowerCase());
    return nav.find(x => LANGS.includes(x)) || 'en';
  }

  /* interactive = the flags switch language in place (thank-you page).
     When false the flags are ordinary links to /fr/, /es/ … and only the
     mobile open/close toggle needs wiring. */
  function wireSwitcher(interactive){
    const box = document.getElementById('lang');
    const cur = document.getElementById('langCur');
    if(!box || !cur) return;
    cur.addEventListener('click', e => {
      e.stopPropagation();
      const open = box.classList.toggle('open');
      cur.setAttribute('aria-expanded', String(open));
    });
    /* Every page switches language by going to that language's URL. The
       generated pages carry an href; the English source pages do not, so
       derive it from the file we are on — /channels.html → /fr/channels.html.
       Nothing translates in place any more, which is why an English page can
       ship with no dictionary at all. */
    box.querySelectorAll('button.lang-b').forEach(b => {
      b.addEventListener('click', () => {
        const href = b.getAttribute('href');
        if(href){ location.href = href; return; }
        const to = b.dataset.lang;
        const file = location.pathname.split('/').pop() || '';
        location.href = (to === 'en' ? './' : to + '/') + file;
      });
    });
    const close = () => {
      box.classList.remove('open');
      cur.setAttribute('aria-expanded','false');
    };
    document.addEventListener('click', e => { if(!box.contains(e.target)) close(); });
    addEventListener('keydown', e => { if(e.key === 'Escape') close(); });
  }

  return {
    t, tf, apply, langs: LANGS,
    get lang(){ return LANG; },
    /* opts:
         { prerendered: true, lang: 'fr' }  — the page's static text is already
           in that language (one URL per language). Nothing is re-translated;
           only the parts JavaScript builds are rendered, in that language.
         { skip: 'css,selectors', onApply: fn } — single-page mode: the text is
           English in the file and swapped in the browser. */
    boot(opts){
      opts = opts || {};
      onApply = opts.onApply || null;
      titleKey = opts.titleKey || '__meta_title';
      descKey  = opts.descKey  || '__meta_desc';

      /* A generated page declares window.PAGE_LANG before this file loads. */
      if(opts.prerendered || window.PAGE_LANG){
        const l = window.PAGE_LANG || opts.lang ||
                  document.documentElement.getAttribute('lang') || 'en';
        LANG = (l === 'en' || DICT[l]) ? l : 'en';
        if(LANG === 'ar') loadArabicFont();
        wireSwitcher(false);
        if(onApply) onApply(LANG);
        return;
      }

      snapshot(opts.skip);
      wireSwitcher(true);
      apply(opts.lang || initial(), false);
    }
  };
})();
